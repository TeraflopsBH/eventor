function catalogueKey(code: string): string {
  return code.toLowerCase().split("_").map((part, index) =>
    index === 0 ? part : part.charAt(0).toUpperCase() + part.slice(1),
  ).join("");
}

/** Translate stable API problem codes; preserve the server title for unknown future codes. */
export function formatApiError(error: ApiError, translate: ApiErrorTranslator): string {
  if (!knownApiErrorCodes.has(error.code)) return `${error.message} [${error.code}]`;
  return translate(`apiErrors.${catalogueKey(error.code)}`);
}
